/**
 * Explicit coverage and error limits per model, from the pooled held-out rows of protocols 1 and 2 (rows predicted without
 * seeing their own record), under what scope.json actually serves. Writes docs/PRICING_EVIDENCE_COVERAGE.md.
 *
 *   npx tsx scripts/pricing-evidence/coverage-limits.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { applyCompetitorUplift } from '../../lib/pricingCalculator';
import { applyPayoutCeiling, cashifyProcessingFee, headlineFromBase, maxPayoutForCashifyPayout } from '../../lib/pricing/payoutCeiling';
import { customerPayout } from '../../lib/pricing/payout';
import { EVIDENCE_DIR } from './evidenceLib';
import scopeJson from '../../lib/pricing/appleCashifyModel/scope.json';

const SCOPE = (scopeJson as unknown as { models: Record<string, { enabled: boolean; mode: string; inferredPolicy: string; storagesGb: number[] }> }).models;
const gbOf = (s: string) => { const m = s.match(/(\d+)(GB|TB)/i); return m ? Number(m[1]) * (m[2].toUpperCase() === 'TB' ? 1024 : 1) : 0; };
const VAL = path.join(EVIDENCE_DIR, 'validation');
const read = (f: string) => fs.readFileSync(path.join(VAL, f), 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l));
const q = (xs: number[], p: number) => { const v = [...xs].sort((a, b) => a - b); return v.length ? v[Math.min(v.length - 1, Math.max(0, Math.ceil(p * v.length) - 1))] : null; };
const pct = (x: number | null) => x == null ? '-' : `${x.toFixed(1)}%`;
const rows = [...read('rows_p1.jsonl'), ...read('rows_p2.jsonl')].filter(r => r.observedOutcome === 'NUMERIC_QUOTE' && r.observedBase != null && r.observedSelling != null);

interface A { n: number; evidence: number; inspect: number; existing: number; rel: number[]; over: number[]; breaches: number; excess: number[]; pricedForBreach: number }
const by: Record<string, A> = {};
for (const r of rows) {
  const a = (by[r.model] ??= { n: 0, evidence: 0, inspect: 0, existing: 0, rel: [], over: [], breaches: 0, excess: [], pricedForBreach: 0 });
  a.n++;
  const entry = SCOPE[r.model];
  const inScope = !!entry?.enabled && entry.storagesGb.includes(gbOf(r.storage));
  const existing = r.existing.kind === 'PRICE' ? r.existing.price : null;
  let equivalent: number | null; let kind: 'evidence' | 'existing' | 'inspect';
  if (!inScope) { equivalent = existing; kind = 'existing'; }
  else if (r.proposed.kind === 'NO_OFFER') { equivalent = null; kind = 'inspect'; }
  else if (r.proposed.kind !== 'PRICE') { equivalent = existing; kind = 'existing'; }
  else if (r.confidence === 'inferred' && entry.inferredPolicy === 'inspect') { equivalent = null; kind = 'inspect'; }
  else if (r.confidence === 'inferred' && entry.inferredPolicy === 'legacy') { equivalent = existing; kind = 'existing'; }
  else { equivalent = r.proposed.price; kind = 'evidence'; }
  a[kind]++;
  if (equivalent == null) continue;
  const err = equivalent - r.observedBase;
  const denom = Math.max(r.observedBase, 0.2 * r.reference);
  if (kind === 'evidence') { a.rel.push(100 * Math.abs(err) / denom); a.over.push(100 * Math.max(0, err) / denom); }
  const c = applyPayoutCeiling({ quote: applyCompetitorUplift(r.reference, equivalent), cashifyHeadlineEquivalent: headlineFromBase(equivalent) });
  if (c.status !== 'ok') { a.inspect++; a[kind]--; continue; }
  const observedPayout = r.observedPayout ?? r.observedSelling - cashifyProcessingFee(r.observedSelling);
  const excess = customerPayout(c.quote, false).payout - maxPayoutForCashifyPayout(observedPayout);
  a.pricedForBreach++;
  if (excess > 0) { a.breaches++; a.excess.push(excess); }
}
const L: string[] = [];
L.push('# iPhone evidence engine: coverage and error limits', '');
L.push('Generated by `scripts/pricing-evidence/coverage-limits.ts` from the pooled held-out rows of protocols 1 and 2 (every row predicted without seeing its own record) under what `scope.json` serves. Quotes are Cashify quotes dated 16-24 Oct 2026; the data is ~30 condition shapes repeated across storages, so effective sample sizes are far below the row counts.', '');
L.push('**What these numbers do and do not say.**');
L.push('- *Coverage* = share of held-out requests the shipped scope answers with a price from the evidence model, from the existing engine, or by sending the customer to inspection.');
L.push('- *Estimate error* = engine Cashify-equivalent vs the observed Cashify base price, as % of max(observed base, 20% of Get Upto), only for rows the evidence model priced.');
L.push('- *Observed-ceiling breach* = the customer payout (after the uplift, the INR 99 fee and the ceiling function, no coupon) is above Cashify\'s ACTUAL payout + min(8%, INR 2,000). The ceiling function guarantees the limit against the ENGINE\'S estimate only; this column is what the business rule is really about, and it is only as good as the estimate. No hard Cashify ceiling is claimed.', '');
L.push('| model | mode | held-out | evidence | existing engine | inspection | est. error median / p90 / p95 / max (evidence rows) | p95 over-estimate | observed-ceiling breaches | breach excess p95 / max (INR) |');
L.push('|---|---|---:|---:|---:|---:|---|---:|---:|---|');
let tot = { n: 0, evidence: 0, existing: 0, inspect: 0, breaches: 0, priced: 0 };
for (const m of Object.keys(by).sort()) {
  const a = by[m]; const e = SCOPE[m];
  tot.n += a.n; tot.evidence += a.evidence; tot.existing += a.existing; tot.inspect += a.inspect; tot.breaches += a.breaches; tot.priced += a.pricedForBreach;
  L.push(`| ${m} | ${e ? (e.enabled ? (e.inferredPolicy === 'price' ? 'all combinations' : e.inferredPolicy === 'inspect' ? 'measured-only' : 'measured + existing') : 'off') : 'not modelled'} | ${a.n} | ${pct(100 * a.evidence / a.n)} | ${pct(100 * a.existing / a.n)} | ${pct(100 * a.inspect / a.n)} | ${a.rel.length ? `${pct(q(a.rel, .5))} / ${pct(q(a.rel, .9))} / ${pct(q(a.rel, .95))} / ${pct(Math.max(...a.rel))}` : '-'} | ${pct(q(a.over, .95))} | ${a.pricedForBreach ? `${a.breaches}/${a.pricedForBreach} (${pct(100 * a.breaches / a.pricedForBreach)})` : '-'} | ${a.excess.length ? `${q(a.excess, .95)} / ${Math.max(...a.excess)}` : '-'} |`);
}
L.push(`| **all** | | ${tot.n} | ${pct(100 * tot.evidence / tot.n)} | ${pct(100 * tot.existing / tot.n)} | ${pct(100 * tot.inspect / tot.n)} | | | ${tot.breaches}/${tot.priced} (${pct(100 * tot.breaches / tot.priced)}) | |`, '');
L.push('Reading guide: a model with a high "existing engine" share is NOT covered by this work; its observed-ceiling result is the old engine\'s and is poor (it ignores touch failure and several other answers). A high "inspection" share is the price of refusing combinations the model has not seen.', '');
fs.writeFileSync(path.join(root(), 'docs/PRICING_EVIDENCE_COVERAGE.md'), L.join('\n') + '\n');
function root() { return path.resolve(__dirname, '../..'); }
