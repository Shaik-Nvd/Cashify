#!/usr/bin/env python3
"""Render docs/PRICING_EVIDENCE_RULES.md: the evidence-backed rules, their scope, supporting cases and confidence.

Usage: python -I scripts/pricing-evidence/render_rules_report.py --evidence data/pricing-evidence --calibration lib/pricing/appleCashifyModel --docs docs
"""
import argparse
import json
import os
import sys
from collections import Counter, defaultdict

sys.stdout.reconfigure(encoding="utf-8")
TRIGGERS = ["Q02", "Q03", "S01", "P01", "P02", "P03"]


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i, _ in enumerate(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def load_jsonl(p):
    return [json.loads(l) for l in open(p, encoding="utf-8") if l.strip()]


def money(n):
    return f"₹{n:,.0f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--evidence", required=True)
    ap.add_argument("--calibration", required=True)
    ap.add_argument("--docs", required=True)
    a = ap.parse_args()
    ms = load_jsonl(os.path.join(a.evidence, "measurements.jsonl"))
    cal = json.load(open(os.path.join(a.calibration, "calibration.json"), encoding="utf-8"))
    scope = json.load(open(os.path.join(a.calibration, "scope.json"), encoding="utf-8"))
    inv = json.load(open(os.path.join(a.evidence, "inventory.json"), encoding="utf-8"))
    cat = inv["catalog"]
    num = [m for m in ms if m["outcome"] == "NUMERIC_QUOTE"]
    L = []
    A = L.append
    A("# iPhone Cashify evidence: pricing rules")
    A("")
    A("Generated by `scripts/pricing-evidence/render_rules_report.py`. Each rule states what was measured, where it applies, how many quotes support it, and whether it is **measured** (shown directly by quotes of the model it is applied to), **inferred** (carried from sibling models / the shared template without confirmation on this model) or **unsupported** (the engine does not price it). Accuracy figures are in `PRICING_EVIDENCE_VALIDATION.md`.")
    A("")
    A("## 1. The three prices that must never be mixed")
    A("")
    A("| price | what it is | relation |")
    A("|---|---|---|")
    A("| **base price** | Cashify's 'Get Upto' for a flawless phone; the engine's *Cashify-equivalent* is on this basis | selling price + ₹20 (2,238 of 2,238 quotes that record both) |")
    A("| **headline selling price** | the figure Cashify shows as the quote | base price - ₹20 IMEI validation fee |")
    A("| **payout after fees** | what the customer is paid | selling price - processing fee: ₹49 up to ₹2,880; ₹69 for ₹4,090-4,190; ₹99 from ₹5,760 (the ranges in between were never observed) |")
    A("")
    A("Fhoneify's own deduction is a flat ₹99 and it charges no IMEI fee, so for the same Cashify-equivalent a Fhoneify customer is structurally about ₹20 ahead before any uplift. The payout ceiling (`lib/pricing/payoutCeiling.ts`) counts that as part of the extra.")
    A("")
    A("## 2. How a quote is built")
    A("")
    A("1. **Reference** R = Cashify's Get Upto for the exact variant (the existing `ReferencePrice` path, unchanged).")
    A("2. **Evidence model** (`lib/pricing/appleCashifyModel`) computes the Cashify-equivalent: R minus the age effect, minus the condition deductions, minus the box/eSIM deductions, never below the model's floor, rounded to ₹10. Every rupee appears in a breakdown labelled `measured`, `inferred` or `rule`.")
    A("3. **Existing uplift** `applyCompetitorUplift` (8% up to ₹20,000 of Get Upto, 6% up to ₹50,000, else 4%; extra capped at ₹2,000) is applied **once**, unchanged.")
    A("4. **Payout ceiling**: the customer payout - after the ₹99 fee and including the first-time coupon - may not exceed the Cashify-equivalent *payout* by more than min(8%, ₹2,000). It only ever lowers a quote or trims the coupon bonus; it never raises anything.")
    A("")
    A("Calibration data (`calibration.json`, `scope.json`, `template.json`) is separate from the logic (`model.ts`). A model is used only if it is enabled in `scope.json` (held-out validation) **and** the storage variant is one that was measured; every other iPhone, and any answer the model cannot read, keeps the existing engine untouched.")
    A("")

    # ---------- R1 trigger evidence (computed)
    def age_shown(m):
        return m["inputs"]["age"]["value"] not in ("not_shown", "unknown", "not_asked")
    asked = [m for m in num if m["inputs"]["warranty"]["value"] == "yes" and m["inputs"]["bill"]["value"] == "yes"]
    rows = []
    for code in TRIGGERS + ["D01", "D04", "D06", "S02", "S04", "P04", "C04", "F05"]:
        sub = [m for m in asked if code in m["deviations"] and not any(t in m["deviations"] for t in TRIGGERS if t != code)]
        if not sub:
            continue
        shown = sum(1 for m in sub if age_shown(m))
        rows.append([f"{code} {cat[code]['name']}", len(sub), shown, len(sub) - shown, "skipped" if shown == 0 else ("asked" if shown == len(sub) else "mixed")])
    A("## 3. Rules")
    A("")
    A("### R1. Cashify skips its age question, and prices the phone as over 11 months old, for exactly six answers")
    A("")
    A("Touch screen not working, screen not original, cracked/broken glass, cracked side/back panel, missing panel, bent/curved panel. It does **not** do so for spots, lines, discoloration, scratches, dents, or a loose screen. Measured as: among quotes with warranty = Yes and bill = Yes and none of the other trigger answers, how often Cashify still showed the age question:")
    A("")
    A(md_table(["answer", "quotes", "age question shown", "skipped", "reading"], rows))
    A("")
    n_age_models = sum(1 for p in cal["models"].values() if p["asks"]["warranty"])
    A(f"Scope: the {n_age_models} models whose flows ask warranty/age (iPhone 15 and later). **Consequence for the form**: today's rule `warrantyVoidedByDiagnostics` also voids warranty for spots, lines, discoloration and a loose screen, which Cashify does not; for models in scope the form now sends the customer's own warranty answer and the model decides. Status: **measured**.")
    A("")
    A("### R2. The age / out-of-warranty effect is applied once, and 'Warranty = No', 'Bill = No' and the R1 answers are the same state")
    A("")
    ow = [m for m in num if m["deviations"] in (["WARRANTY_NO"], ["BILL_NO"], ["AGE:Above 11 months"])]
    byk = defaultdict(set)
    for m in ow:
        byk[(m["model_key"], m["storage"], m["observed_date"])].add(m["base"])
    same = sum(1 for v in byk.values() if len(v) == 1)
    A(f"In {len(byk)} variant-days where warranty No, bill No and age 'above 11 months' were all quoted, {same} gave one identical price. Combining a trigger answer with any age/warranty answer never adds a second age deduction (pairs T0556-T0563: panel/body/spots + cracked glass). The deduction is `a + b x reference` per age step (3-6, 6-11, over 11 months), fitted per model; for models whose variants do not follow one line (iPhone 15, 15 Plus, 16e) the measured percentage per variant is stored and preferred. Status: **measured** per model/variant; for a storage variant that was not measured it is **inferred** from the model's line.")
    A("")
    A("### R3. Screen faults share one deduction: the largest wins")
    A("")
    pairs = [m for m in num if m["family"] == "pair_jsonl"]
    singles = {}
    for m in num:
        if m["model_key"] == "iPhone 18 Pro Max" and m["storage"] == "2TB" and m["class"] == "single_defect" and m["observed_date"] == "2026-10-22":
            singles[m["deviations"][0]] = m["variant_get_upto"] - m["base"]
    pstat = defaultdict(lambda: [0, 0])
    for p in pairs:
        c1, c2 = p["defect_codes"]
        ded = p["variant_get_upto"] - p["base"]
        key = tuple(sorted((cat[c1]["group"], cat[c2]["group"])))
        pstat[key][0] += 1
        if ded == singles[c1] + singles[c2]:
            pstat[key][1] += 1
    A("Cracked glass / chipped glass / scratches (S), spots (D01-D03), lines (D04-D05), discoloration (D06-D07), touch failure (Q02) and non-original screen (Q03) are priced as one group: the largest of them applies, plus the single age effect when cracked glass, touch or non-original forces it. Evidence: all 28 Screen x Display pairs and the Screen x Panel pairs on the iPhone 18 Pro Max 2 TB are explained exactly by this rule, and the multi-fault checklist shapes M08, M11, M12 on 15 other models.")
    A("")
    A(md_table(["pair category (iPhone 18 Pro Max 2 TB)", "pairs observed", "equal to the sum of the singles", "differ from the sum"], [[" x ".join(k), v[0], v[1], v[0] - v[1]] for k, v in sorted(pstat.items())]))
    nonadd = sum(v[0] - v[1] for v in pstat.values())
    A("")
    A(f"**All {nonadd} non-additive pairs involve a screen fault** and are reproduced by R2 (age once) + R3 (largest screen fault) + R4 (body absorbed under cracked glass); the 124 additive pairs (63 functional x functional, display x body/panel/bent, ...) match plain addition. The source's claim that 36 differ is therefore **confirmed and explained, not just counted**. The pair plan never combined a functional fault with a physical one, so additivity *across* those groups is only supported by the multi-fault checklist shapes (e.g. M09), not pair by pair.")
    A("")
    A("### R4. Body damage and panel damage share one deduction (largest wins); under cracked glass most of the body deduction disappears")
    A("")
    A("Body scratches/dents (C01-C04) and panel/frame damage (P01-P04) compete (checklist M09: body + loose screen = the loose-screen deduction). When cracked glass has already forced the aged state, body damage adds only 37% (more than 2 scratches, 1-2 dents), 48% (major dents) or 0% (1-2 scratches) of its normal deduction, and a loose screen deducts the same as a cracked panel. Measured on the iPhone 18 Pro Max 2 TB only (pairs T0556-T0559, T0560-T0563); the percentages are **inferred** for every other model. Status: panel/body group **measured**; the under-glass reduction **measured once, inferred elsewhere**.")
    A("")
    A("### R5. Wi-Fi and Bluetooth overlap; the other functional faults add up")
    A("")
    A("Wi-Fi and Bluetooth together deduct the same as either alone (≈30-31% of price). Cameras, speaker/receiver/microphone/charging port, buttons, vibration, proximity and Face ID add up (63 of 63 observed functional pairs on the 18 Pro Max are additive; checklist shapes M02, M04, M05, M07 on 15 models). Battery in service vs battery health 80-85% is treated as one group (largest wins): **inferred** (no pair measured it).")
    A("")
    A("### R6. Each deduction is either a fixed rupee amount or a share of the price, and which one depends on the generation")
    A("")
    fam = defaultdict(lambda: defaultdict(Counter))
    for name, p in cal["models"].items():
        for cls, c in p["classes"].items():
            fam[p["family"]][cls][c["kind"]] += 1
    rows = []
    for cls in ["display", "cracked", "touch", "orig", "body", "panel", "cam", "fminA", "fminB", "prox", "wifi", "face", "batt"]:
        rows.append([cls] + [("/".join(f"{k}{v}" for k, v in fam[f][cls].items()) if fam[f][cls] else "-") for f in ["14", "15", "16", "17plus"]])
    A(md_table(["condition class", "iPhone 14", "iPhone 15", "iPhone 16", "iPhone 17 / Air / 18"], rows))
    A("")
    A("(fixed = rupees independent of the variant's price; pct = share of the variant's own Get Upto; counts are models.) Body and panel switch from fixed rupees (14-16) to a share of the price (17, Air, 18); Wi-Fi/Bluetooth and Face ID are shares everywhere; screen, cameras, buttons, battery and the box are fixed rupees. Decided from storage-variant comparisons where a model has several variants, otherwise taken from its generation: **measured** vs **inferred** is recorded per model below.")
    A("")
    A("### R7. A floor applies only once the over-11-months state is forced")
    A("")
    fl = [(n, p["floor"]) for n, p in cal["models"].items() if p.get("floor")]
    A("Heavily damaged phones stop losing value at a plateau: several different shapes quote the same share of the price. The plateau is " + ", ".join(f"{n} {f['value'] * 100:.1f}% of the {'aged price' if f['basis'] == 'aged' else 'reference'}" for n, f in fl[:6]) + (f" and {len(fl) - 6} more" if len(fl) > 6 else "") + ". It never appears in the younger states, which is why a phone with seventeen simultaneous functional faults is *not* floored (see R10; the engine sends those to inspection). The floor basis (reference vs aged price) is chosen per model by which explains that model's plateau. Status: **measured** where listed, otherwise no floor is applied (the safe direction).")
    A("")
    A("### R8. Box, charger, eSIM")
    A("")
    boxes = [p["boxNo"] for p in cal["models"].values() if p["family"] != "14" and p["boxNo"]["support"] == "measured"]
    esim_models = [n for n, p in cal["models"].items() if p.get("eSimDualPct") is not None]
    aged_asks = [n for n, p in cal["models"].items() if p["asks"]["warranty"]]
    A(f"Missing box: a fixed amount ({money(min(b['base'] for b in boxes))}-{money(max(b['base'] for b in boxes))} across the {len(boxes)} measured iPhone 15-18 models; about ₹1,200 on the 14) that is smaller once the aged state applies (₹1,500 against ₹2,250 on the iPhone 18 Pro Max). Missing charger: no deduction wherever the question was offered (the 18 series; most flows do not offer it). Dual eSIM: about 5% of the price on the {len(esim_models)} models whose flow asks it ({', '.join(sorted(esim_models))}). Status: box **measured**; charger **measured for the 18 series only**.")
    A("")
    A("### R9. Cannot make or receive calls")
    A("")
    A("On its own it quotes a fixed ₹1,200 scrap (₹1,180 selling price) - measured on the iPhone 18 Pro Max only (**inferred** for every other model). The only combination measured with it (calls + touch + screen + Wi-Fi + Face ID + Bluetooth) was declined by Cashify in every model that was tried; other combinations were never measured, so the engine sends *any* combination with another fault to inspection rather than guessing. Never stored as ₹0.")
    A("")
    A("### R10. Cashify declines some conditions ('device seems to have very little value')")
    A("")
    no = [m for m in ms if m["outcome"] == "NO_OFFER"]
    shapes = Counter(",".join(m["deviations"]) for m in no)
    shape_text = "; ".join(f"`{('Q01,Q02,Q03,F05,F08,F14' if s.startswith('Q01') else 'all 17 functional faults (F01-F17)')}` x {n}" for s, n in sorted(shapes.items(), key=lambda kv: -kv[1]))
    m20 = [m for m in num if len([d for d in m["deviations"] if d.startswith("F")]) >= 15]
    ratios = sorted(m["base"] / m["variant_get_upto"] for m in m20)
    A(f"{len(no)} quotes were declined across {len(shapes)} distinct conditions ({shape_text}). The all-faults phone that Cashify did quote ranged from {ratios[0] * 100:.1f}% to {ratios[-1] * 100:.1f}% of the price ({len(m20)} quotes), so no rule can be read from it. The engine routes both conditions to manual inspection instead of inventing a price.")
    A("")
    A("## 4. Parameters, per model")
    A("")
    A("Class values are the deduction at weight 1 for that class (rupees if fixed, share of the price if pct); `?` marks a value that is **inferred** (not pinned down by that model's own quotes). Age is the share of the variant's price deducted at 3-6 / 6-11 / over 11 months (measured per variant where available).")
    A("")
    hdr = ["model", "storages measured", "age 3-6 / 6-11 / >11 (per variant, %)", "floor", "box", "screen group display/cracked/touch/orig", "body / panel", "cameras", "Wi-Fi / Face ID", "scope"]
    rows = []
    for name, p in sorted(cal["models"].items()):
        def v(cls):
            c = p["classes"][cls]
            val = f"{c['value'] * 100:.1f}%" if c["kind"] == "pct" else f"₹{c['value']:,.0f}"
            return val + ("" if c["support"] == "measured" else "?")
        ages = []
        if p.get("ageByStorage"):
            for gb in sorted(p["ageByStorage"], key=int):
                t = p["ageByStorage"][gb]
                ages.append(f"{int(gb) // 1024 if int(gb) >= 1024 else gb}{'TB' if int(gb) >= 1024 else 'GB'}: " + "/".join("-" if t[k] is None else f"{t[k] * 100:.1f}" for k in ["1", "2", "3"]))
        elif p["age"]:
            ages.append("law only")
        else:
            ages.append("not asked")
        fl = p.get("floor")
        sc = scope["models"].get(name, {})
        rows.append([name, ", ".join(f"{g // 1024}TB" if g >= 1024 else f"{g}GB" for g in p["storagesGb"]), "; ".join(ages),
                     f"{fl['value'] * 100:.1f}% {fl['basis']}" if fl else "-",
                     f"₹{p['boxNo']['base']:,.0f}/{p['boxNo']['aged']:,.0f}" + ("" if p["boxNo"]["support"] == "measured" else "?"),
                     " / ".join(v(c) for c in ["display", "cracked", "touch", "orig"]), f"{v('body')} / {v('panel')}", v("cam"), f"{v('wifi')} / {v('face')}",
                     "ENABLED" if sc.get("enabled") else "existing engine"])
    A(md_table(hdr, rows))
    A("")
    A("## 5. Not supported (falls back, never guessed)")
    A("")
    A("- Any iPhone model or storage variant without its own quotes (iPhone 11, 12, 13 and earlier, 14 Plus, 14 Pro Max, SE, XR, XS, and storage variants that were not measured) - existing engine, unchanged.")
    A("- Models that did not meet the held-out thresholds - existing engine (see the scope table in `PRICING_EVIDENCE_VALIDATION.md`).")
    A("- Conditions Cashify declines, and phones with ten or more functional faults - manual inspection (422 MANUAL_INSPECTION_REQUIRED), not a price.")
    A("- Answers the model cannot map (unknown hardware ids such as hinge, S-Pen) - existing engine.")
    A("- Larger combinations: only ~2 measured shapes have more than 5 faults. They are priced by the same group rules, which hold on those shapes, but they are the least validated region.")
    A("")
    with open(os.path.join(a.docs, "PRICING_EVIDENCE_RULES.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", os.path.join(a.docs, "PRICING_EVIDENCE_RULES.md"))


if __name__ == "__main__":
    main()
