#!/usr/bin/env python3
"""Render docs/PRICING_EVIDENCE_VALIDATION.md from the held-out validation output. Every number is computed here.

Usage: python -I scripts/pricing-evidence/render_validation_report.py --evidence data/pricing-evidence --docs docs
"""
import argparse
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

PROTOCOLS = [
    ("p1", "Unseen condition shapes", "5 folds. Every measurement of a given model + exact set of deviations (all storages, dates and duplicate exports) is in the same fold, so a copied or repeated case can never be an 'independent' test."),
    ("p2", "Unseen storage variants", "Holds out the r-th storage of every model (r = 0..3) and fits on every other variant. Tests whether fixed-rupee versus proportional behaviour was identified correctly."),
    ("p3", "Later dates", "Fits only on quotes dated up to 2026-10-17 (mostly one 512 GB variant per model) and predicts quotes dated 2026-10-22 and later. A deliberately hard test: little training data, many unseen shapes, a week of Cashify price movement."),
    ("p4", "Unseen models", "Leave one model out: every parameter is borrowed from the other models of the same generation. Measures how far calibration transfers between models; NOT a licence to price models that have no quotes."),
]


def fmt(n):
    if n is None:
        return "-"
    if isinstance(n, float):
        return f"{n:,.1f}" if abs(n) < 100 else f"{n:,.0f}"
    return f"{n:,}"


def money(n):
    return "-" if n is None else f"₹{n:,.0f}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i, _ in enumerate(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def summ_row(label, s):
    return [label, f"{s['predicted']}/{s['n']}", money(s["mae"]), money(s["median"]), money(s["p90"]), money(s["p95"]), money(s["max"]), fmt(s["bias"]), f"{s['within500']}%", f"{s['within2pct']}%"]


def mode_text(dec):
    return dec["mode"] + " [" + ",".join(dec.get("failedMeasured", []) + dec.get("failedInferred", [])) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--evidence", required=True)
    ap.add_argument("--docs", required=True)
    a = ap.parse_args()
    val = os.path.join(a.evidence, "validation")
    summary = json.load(open(os.path.join(val, "summary.json"), encoding="utf-8"))
    decisions = json.load(open(os.path.join(val, "scope_decision.json"), encoding="utf-8")) if os.path.exists(os.path.join(val, "scope_decision.json")) else {}
    L = []
    A = L.append
    A("# iPhone Cashify evidence: held-out validation")
    A("")
    A("Generated by `scripts/pricing-evidence/render_validation_report.py` from `data/pricing-evidence/validation/` (produced by `validate-evidence-engine.ts`). The existing and the evidence-calibrated engine are scored on **exactly the same held-out Cashify quotes**.")
    A("")
    A("**How to read the numbers.** Error = the engine's Cashify-equivalent minus the observed Cashify *base price* (headline selling price + ₹20; the same basis as Cashify's Get Upto, which is the reference the engine starts from). Positive = the engine quotes above Cashify, which is the costly direction because Fhoneify's uplift sits on top. 'Existing engine' is today's `priceDevice` path with the form's current warranty-voiding rule; 'evidence engine' is `appleCashifyModel` refitted without the test rows; 'evidence + fallback' prices anything the evidence engine will not price with the existing engine, which is what production would do.")
    A("")
    A("**Honest limits.**")
    A("- The *structure* of the model (age applied once, largest-wins groups, fixed versus proportional values, floors) was found by studying the whole dataset, including rows that later serve as test rows. The held-out protocols are honest about parameter estimation (no test row informs a fitted number) but optimistic about structure. The genuinely blind test is the next collection round (see `PRICING_EVIDENCE_NEXT_QUOTES.md`) against the thresholds fixed below.")
    A("- Most of the dataset replicates ~30 condition shapes across storages and models, so effective sample sizes are far smaller than row counts: protocol 1 holds out whole shapes for that reason.")
    A("- The calibration was fitted on Cashify quotes dated 16-24 Oct 2026. Nothing here shows the rules stay stable as Cashify changes its tables.")
    A("")
    for key, title, desc in PROTOCOLS:
        s = summary["protocols"].get(key)
        if not s:
            continue
        A(f"## {key.upper()}: {title}")
        A("")
        A(desc)
        A("")
        o = s["overall"]
        A(md_table(["engine", "priced/quotes", "mean abs error", "median", "p90", "p95", "max", "bias", "within ₹500", "within 2%"],
                   [summ_row("existing engine", o["existing"]), summ_row("evidence engine (supported rows only)", o["proposed"]), summ_row("evidence + existing fallback", o["proposedWithExistingFallback"])]))
        A("")
        n = s["noOffer"]
        A(f"**No-offer handling** ({n['existing']['observedNoOffer']} quotes Cashify declined): the existing engine quoted a price for {n['existing']['quotedAPriceWhereCashifyDeclined']} of them (it has no concept of a decline). The evidence engine routed {n['proposed']['predictedNoOffer']} to inspection, could not read {n['proposed']['unsupported']}, and quoted a price for {n['proposed']['quotedAPriceWhereCashifyDeclined']}. It sent {n['proposed']['declinedWhereCashifyQuoted']} quotes Cashify did price to inspection (lost instant quotes, not wrong prices).")
        A("")
        A("**By model** (existing vs evidence engine, same rows):")
        A("")
        rows = []
        for g in s["byModel"]:
            e, p = g["existing"], g["proposed"]
            dec = decisions.get(g["key"])
            tag = "" if key not in ("p1", "p2") or not dec else ("ENABLED" if dec["enabled"] else "kept: " + mode_text(dec))
            rows.append([g["key"], f"{p['predicted']}/{p['n']}", money(e["mae"]), money(p["mae"]), money(p["median"]), money(p["p95"]), money(p["max"]), f"{p['within2pct']}%", tag])
        A(md_table(["model", "priced/quotes", "existing MAE", "evidence MAE", "evidence median", "evidence p95", "evidence max", "within 2%", "scope (p1+p2)"], rows))
        A("")
        A("**By defect group** (weak groups are not hidden by the overall mean):")
        A("")
        A(md_table(["group", "priced/quotes", "existing MAE", "evidence MAE", "evidence p95", "evidence max", "within 2%"],
                   [[g["key"], f"{g['proposed']['predicted']}/{g['proposed']['n']}", money(g["existing"]["mae"]), money(g["proposed"]["mae"]), money(g["proposed"]["p95"]), money(g["proposed"]["max"]), f"{g['proposed']['within2pct']}%"] for g in s["byDefectGroup"]]))
        A("")
        A("**By combination size** (number of deviations from the flawless baseline):")
        A("")
        A(md_table(["deviations", "priced/quotes", "existing MAE", "evidence MAE", "evidence p95", "evidence max"],
                   [[g["key"], f"{g['proposed']['predicted']}/{g['proposed']['n']}", money(g["existing"]["mae"]), money(g["proposed"]["mae"]), money(g["proposed"]["p95"]), money(g["proposed"]["max"])] for g in s["byCombinationSize"]]))
        A("")
        if s.get("byConfidence"):
            A("**By the model's own confidence label** (does 'inferred' really mean less accurate?):")
            A("")
            A(md_table(["confidence", "quotes", "evidence MAE", "evidence p95", "evidence max"],
                       [[g["key"], g["proposed"]["predicted"], money(g["proposed"]["mae"]), money(g["proposed"]["p95"]), money(g["proposed"]["max"])] for g in s["byConfidence"]]))
            A("")
        # worst cases
        rows_p = [json.loads(l) for l in open(os.path.join(val, f"rows_{key}.jsonl"), encoding="utf-8") if l.strip()]
        priced = [r for r in rows_p if r["observedOutcome"] == "NUMERIC_QUOTE" and r["proposed"]["kind"] == "PRICE" and r["observedBase"] is not None]
        for r in priced:
            r["err"] = r["proposed"]["price"] - r["observedBase"]
        over = sorted(priced, key=lambda r: -r["err"])[:5]
        under = sorted(priced, key=lambda r: r["err"])[:5]

        def case_block(r):
            ex = r["existing"]
            out = [f"- **{r['model']} {r['storage']}**, {r['date']}, source `{r['source']}`, answers: {', '.join(r['deviations']) or 'flawless'}",
                   f"  - Cashify: Get Upto {money(r['reference'])}; base {money(r['observedBase'])}, selling {money(r['observedSelling'])}, payout after fees {money(r['observedPayout'])}",
                   f"  - evidence engine {money(r['proposed']['price'])} (error {r['err']:+,.0f}, confidence {r['confidence']}); existing engine {money(ex['price']) if ex['kind'] == 'PRICE' else ex['kind']}"]
            if r.get("breakdown"):
                out.append("  - evidence breakdown: " + "; ".join(f"{b[0]} -{b[1]:,} [{b[2]}]" + (f" ({','.join(b[3])})" if b[3] else "") for b in r["breakdown"]))
            return "\n".join(out)

        A("**Worst over-quotes** (evidence engine above Cashify), with the exact source and the full calculation:")
        A("")
        A("\n".join(case_block(r) for r in over))
        A("")
        A("**Worst under-quotes**:")
        A("")
        A("\n".join(case_block(r) for r in under))
        A("")
    if decisions:
        A("## Scope decision (protocols 1 and 2 pooled, held-out rows only)")
        A("")
        A("Thresholds, fixed before the per-model numbers were read and applied identically to every model:")
        A("")
        A("| # | threshold | why |")
        A("|---|---|---|")
        A("| T1 | median relative error <= 1.0% | most quotes should be indistinguishable from Cashify's own rounding and day-to-day movement (the Get Upto itself moved ~1% in a week) |")
        A("| T2 | 90th-percentile relative error <= 5% | a typical bad case is still a small share of the price |")
        A("| T3 | 95th-percentile OVER-quote <= 3% | quoting above Cashify is the costly direction: the uplift (up to 8%) sits on top, and the owner's ceiling is defined against the true Cashify payout |")
        A("| T4 | mean absolute error <= 50% of the existing engine's on the same rows | it must be clearly better, not marginally |")
        A("| T5 | >= 100 held-out quotes covering >= 10 distinct condition shapes (model level); >= 30 quotes over >= 5 shapes for the measured/inferred subsets (T5s) | otherwise there is not enough evidence to judge. The subset floor is lower than the model floor and is a judgement call to approve |")
        A("| T6 | declined (inspection/unsupported) share <= 15% | an engine that refuses most requests is not an engine |")
        A("| T7 | worst single over-quote <= 10% of that day's Get Upto | percentiles alone can hide one very large over-quote |")
        A("")
        A("Relative error = |engine - Cashify base| / max(Cashify base, 20% of that day's Get Upto), so a floor quote of a few thousand rupees is not judged against itself.")
        A("")
        A("Modes: **all** prices every supported combination; **measured-only** prices combinations the model's own quotes cover and sends unmeasured ('inferred') combinations to inspection; **off** keeps the existing engine. Pooled held-out rows of protocols 1 and 2.")
        A("")
        rows = []
        for m, d in decisions.items():
            def cell(part):
                x = d.get(part)
                if not x:
                    return ["-"] * 5
                y = x["metrics"]
                return [y["quotes"], f"{y['medianRelPct']:.2f}%", f"{y['p90RelPct']:.2f}%", f"{y['p95OverPct']:.2f}%", f"{money(y['maeEvidence'])} vs {money(y['maeExisting'])}"]
            failed = ", ".join(d.get("failedMeasured", [])) or "-"
            failed_inf = ", ".join(d.get("failedInferred", [])) or "-"
            rows.append([m, d["mode"]] + cell("measured") + cell("inferred") + [f"{100 * d['declinedShare']:.0f}%", failed, failed_inf])
        A(md_table(["model", "mode", "meas n", "meas med", "meas p90", "meas p95 over", "meas MAE (new vs old)", "inf n", "inf med", "inf p90", "inf p95 over", "inf MAE (new vs old)", "declined", "meas fails", "inf fails"], rows))
        A("")
    with open(os.path.join(a.docs, "PRICING_EVIDENCE_VALIDATION.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", os.path.join(a.docs, "PRICING_EVIDENCE_VALIDATION.md"))


if __name__ == "__main__":
    main()
