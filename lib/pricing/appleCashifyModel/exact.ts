import exactJson from './exact.json';
import { ageStateOf, parseAnswers, type ModelProfile, type ParsedAnswers } from './model';
import type { DiagnosticsType } from '../../pricingCalculator';

/**
 * Exact matches against the Cashify quotations the testing team collected.
 *
 * A request whose model, capacity and answers equal a recorded Cashify quote is answered with that recorded Cashify-equivalent
 * (the base price, i.e. selling price + INR 20) - the rules in model.ts are for everything that was not recorded. Two things keep
 * this honest:
 *  - The reference price moves between collection dates. A recorded quote carries the Get Upto it was collected against (G0).
 *    With the same reference the recorded amount is returned unchanged; otherwise the recorded amount is carried to the current
 *    reference by the model's own change between G0 and the current reference (or proportionally when the model cannot price it).
 *  - Several records of the same configuration are not averaged: the one collected against the same reference wins, else the newest.
 * Conditions Cashify declined (no offer) are recorded the same way and stay explicit no-offer outcomes.
 *
 * Generated by scripts/pricing-evidence/build-exact-index.ts. Pure and deterministic.
 */

/** [collection date (YYYY-MM-DD) or null, Get Upto at collection, recorded base price or null when Cashify declined] */
export type ExactEntry = [string | null, number, number | null];
export interface ExactIndex { version: string; models: Record<string, Record<string, Record<string, ExactEntry[]>>> }
export const EXACT = exactJson as unknown as ExactIndex;

/**
 * The part of the answers Cashify prices on. For a calibrated model the age/warranty/bill answers are reduced to the
 * over-11-months state they produce (several answers are the same Cashify state); for a model without a profile the
 * raw answers are kept.
 */
/** Models whose recorded quotes show the charger answer changing the price (iPhone X: INR 300). Elsewhere it is not priced. */
const CHARGER_PRICED = new Set(['iPhone X']);
export const chargerMissing = (d: DiagnosticsType) => !(d.charger === true || (d.accessories ?? []).includes('charger'));

export function exactKey(profile: ModelProfile | null, a: ParsedAnswers, modelKey?: string, noCharger?: boolean): string {
  const parts = [a.codes.join(','), a.callsFailed ? 'noCalls' : '', a.boxMissing ? 'noBox' : '', a.dualEsim ? 'dualEsim' : ''];
  if (modelKey && CHARGER_PRICED.has(modelKey) && noCharger) parts.push('noCharger');
  if (profile) {
    const { state } = ageStateOf(a, profile);
    parts.push(`state${state}`);
    // eSIM only matters where the model's flow asks it
    if (!profile.asks.eSim) parts[3] = '';
  } else {
    parts.push(`w${a.warranty}`, `b${a.validBill}`, `a${a.mobileAge}`);
  }
  return parts.join('|');
}

export interface ExactMatch { entry: ExactEntry; entries: number; key: string }

/** The recorded entry to use for the given current reference, or null when none was recorded. */
export function findExact(modelKey: string, storageGb: number, profile: ModelProfile | null, diagnostics: DiagnosticsType, reference: number): ExactMatch | null {
  const byStorage = EXACT.models[modelKey]?.[String(storageGb)];
  if (!byStorage) return null;
  const a = parseAnswers(diagnostics);
  if (a.unsupported.length) return null;
  const key = exactKey(profile, a, modelKey, chargerMissing(diagnostics));
  const entries = byStorage[key];
  if (!entries?.length) return null;
  const same = entries.filter(e => e[1] === reference);
  const pool = same.length ? same : entries;
  // newest collection date wins (undated records are the oldest); ties go to the closest reference
  const best = [...pool].sort((x, y) => (y[0] ?? '').localeCompare(x[0] ?? '') || Math.abs(x[1] - reference) - Math.abs(y[1] - reference))[0];
  return { entry: best, entries: entries.length, key };
}
